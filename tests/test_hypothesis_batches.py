def test_calculation_unit_query_scope_reports_finite_indexed_rules():
    """多个 Query 越界时只返回有限的数组路径和稳定规则码。"""

    queries = [
        _long_query("thermochemistry scope") + " with expected thermodynamics",
        _long_query("default criteria scope")
        + " with program default bond length criteria",
        _long_query("convergence scope") + " within typical convergence/RMSD",
    ]

    with pytest.raises(ValueError) as error:
        HypothesisAgent._validate_query_angles(
            queries,
            len(queries),
            calculation_unit=_CALCULATION_UNIT_QUERY_FIXTURE,
        )

    assert str(error.value) == (
        'calculation_unit_scope.v1:[{"path":"/0","rule":"undeclared_thermochemistry"},'
        '{"path":"/1","rule":"undeclared_acceptance_threshold"},'
        '{"path":"/2","rule":"undeclared_acceptance_threshold"}]'
    )


