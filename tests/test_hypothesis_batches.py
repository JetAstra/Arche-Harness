def test_calculation_unit_is_propagated_to_comparisons_and_synthesis(monkeypatch):
    """有固定单元时三类比较输入和 synthesis 校验共享同一最小范围。"""

    calls = []
    specifications = {}

    def fake_call_model_stage(
        *, stage_name, base_input, specification, reserved_stage_index=None
    ):
        del reserved_stage_index
        calls.append((stage_name, base_input))
        specifications[stage_name] = specification
        if stage_name == "relationship":
            return {"relationship": "merge", "reason": "A 与 B 可合并。"}
        if stage_name == "merge":
            return specification.domain_validator(
                {
                    "strategy_name": "固定单元合成",
                    "reasoning": "保留给定 calculation_unit。",
                }
            )
        return {
            "analysis": "A 更适合固定单元。",
            "reasoning": "A 保留给定条件。",
            "winner": "A",
            "loser": "B",
        }

    agent = HypothesisAgent(comparison_workers=1)
    monkeypatch.setattr(agent, "_call_model_stage", fake_call_model_stage)
    context = {
        "scientific_question": "解释固定计算单元",
        "chemistry_context": {
            "calculation_unit": _CALCULATION_UNIT_HYPOTHESIS_FIXTURE,
        },
    }
    hypothesis_a = {
        "hypothesis_id": "h-a",
        "strategy_name": "A",
        "reasoning": "RA",
        "source_query_angles": ["固定计算单元的端点与路径直接观测 A"],
    }
    hypothesis_b = {
        "hypothesis_id": "h-b",
        "strategy_name": "B",
        "reasoning": "RB",
        "source_query_angles": ["固定计算单元的端点与路径直接观测 B"],
    }

    agent._classify_relationship(hypothesis_a, hypothesis_b, context)
    agent._synthesize_hypothesis_pair(
        hypothesis_a,
        hypothesis_b,
        "merge",
        calculation_unit=_CALCULATION_UNIT_HYPOTHESIS_FIXTURE,
    )
    agent._rank_strategies([hypothesis_a, hypothesis_b], context, [])

    expected_context = {
        "calculation_unit": _CALCULATION_UNIT_HYPOTHESIS_FIXTURE,
    }
    assert [stage for stage, _ in calls] == ["relationship", "merge", "rank"]
    assert all(
        base_input.get("chemistry_context") == expected_context
        for _, base_input in calls
    )
    with pytest.raises(ValueError, match="calculation_unit"):
        specifications["merge"].domain_validator(
            {
                "strategy_name": "越界合成",
                "reasoning": (
                    "Replace the required B3LYP calculation with GFN2-xTB and use a gas-phase approximation."
                ),
            }
        )

    calls.clear()
    specifications.clear()
    ordinary_context = {"scientific_question": "普通任务"}
    agent._classify_relationship(hypothesis_a, hypothesis_b, ordinary_context)
    agent._synthesize_hypothesis_pair(hypothesis_a, hypothesis_b, "merge")
    agent._rank_strategies([hypothesis_a, hypothesis_b], ordinary_context, [])
    assert all("chemistry_context" not in base_input for _, base_input in calls)


