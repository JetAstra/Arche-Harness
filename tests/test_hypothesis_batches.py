def _manifest_model_requests(task_root, manifest):
    """从正式清单逐引用读取实际提交给 provider 的模型请求。"""

    requests = []
    for stage in manifest["stages"]:
        if stage["stage_kind"] != "model":
            continue
        request_ref = stage["attempts"][-1]["request_ref"]
        request_path = task_root / request_ref["relative_path"]
        requests.append((stage["stage"], json.loads(request_path.read_text())))
    return requests


def _run_hypothesis_batch_formally(tmp_path, agent, arguments, operation_id):
    """通过公开 operation 入口运行一批假设并返回规范生成结果。"""

    operation_arguments = dict(arguments)
    retrieval_result = operation_arguments.pop("initial_retrieval_phase")
    result = agent.run_hypothesis_operation(
        task_root=str(tmp_path),
        operation_instance_id=operation_id,
        initial_retrieval_phase=retrieval_result,
        **operation_arguments,
    )
    return result["hypothesis_result"]


