def _envelope(content, *, finish_reason="stop"):
    return {
        "id": "test-trace",
        "choices": [
            {
                "finish_reason": finish_reason,
                "message": {"content": content},
            }
        ],
    }


def _dynamic_input(messages):
    """读取统一 user envelope 中真正交给当前模型阶段的输入。"""

    return json.loads(messages[1]["content"])["base_input"]


def _claim(statement, rationale):
    """构造一项合法原子主张，避免测试夹具重复协议细节。"""

    return {"statement": statement, "rationale": rationale}


